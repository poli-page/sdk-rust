import { CONCEPT_IDIOM_PAGE, getProfile, MIGRATION_PAGE } from './profiles.js';
/**
 * The sidebar of a site of the given profile (`sdk` by default).
 *
 * `pages` lists the site's pages, relative to `src/content/docs/`. The `sdk`
 * sidebar ignores it. The `integration` sidebar takes from it the optional
 * pages it shows: `concepts/<idiom>.mdx` pages, after the required concepts
 * in file-name order, and `support/migration.mdx`, last in Support.
 */
export function buildSidebar(profile = 'sdk', pages = []) {
    return profile === 'integration' ? integrationSidebar(pages) : sdkSidebar();
}
function sdkSidebar() {
    return [
        {
            label: 'Getting started',
            items: [
                { slug: 'getting-started/install' },
                { slug: 'getting-started/quick-start' },
            ],
        },
        {
            label: 'Concepts',
            items: [
                { slug: 'concepts/authentication' },
                { slug: 'concepts/render-modes' },
                { slug: 'concepts/output-handling' },
                { slug: 'concepts/configuration' },
                // Starlight v0.39 requires `autogenerate` items to be nested inside
                // a labeled group, rather than being a labeled item themselves.
                { label: 'More concepts', items: [{ autogenerate: { directory: 'concepts' } }] },
            ],
        },
        {
            label: 'Production',
            items: [
                { slug: 'production/errors' },
                { slug: 'production/retries-and-idempotency' },
                { slug: 'production/cancellation' },
                { slug: 'production/observability' },
            ],
        },
        {
            label: 'Reference',
            items: [
                { slug: 'reference/client' },
                { label: 'Methods', items: [{ autogenerate: { directory: 'reference/methods' } }] },
                { slug: 'reference/types' },
                { slug: 'reference/errors' },
                { slug: 'reference/runtime-support' },
            ],
        },
        {
            label: 'Support',
            items: [
                { slug: 'support/migration' },
                { slug: 'support/changelog' },
                { slug: 'support/license' },
            ],
        },
    ];
}
const slugOf = (page) => ({ slug: page.replace(/\.mdx$/, '') });
const SECTIONS = [
    { dir: 'getting-started', label: 'Getting started' },
    { dir: 'concepts', label: 'Concepts' },
    { dir: 'production', label: 'Production' },
    { dir: 'reference', label: 'Reference' },
    { dir: 'support', label: 'Support' },
];
function integrationSidebar(pages) {
    const { requiredPages } = getProfile('integration');
    const required = new Set(requiredPages);
    // Listed one by one rather than through `autogenerate`: an autogenerated
    // `concepts` group would repeat the required concepts pages.
    const idioms = pages.filter((p) => CONCEPT_IDIOM_PAGE.test(p) && !required.has(p)).sort();
    const migration = pages.includes(MIGRATION_PAGE) ? [MIGRATION_PAGE] : [];
    const extras = {
        concepts: idioms,
        support: migration,
    };
    // Each section lists its required pages in profile order, then its extras.
    return SECTIONS.map(({ dir, label }) => ({
        label,
        items: [
            ...requiredPages.filter((p) => p.startsWith(`${dir}/`)),
            ...(extras[dir] ?? []),
        ].map(slugOf),
    }));
}
